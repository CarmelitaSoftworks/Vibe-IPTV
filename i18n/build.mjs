// Genera las copias del diccionario para cada app a partir de i18n/en.json.
// Generates each app's copy of the dictionary from i18n/en.json.
//   node i18n/build.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const en = JSON.parse(readFileSync(join(root, 'i18n/en.json'), 'utf8'));
const sorted = Object.fromEntries(Object.entries(en).sort(([a], [b]) => a.localeCompare(b, 'es')));
const json = JSON.stringify(sorted, null, 2) + '\n';

writeFileSync(join(root, 'i18n/en.json'), json);
writeFileSync(join(root, 'web/js/i18n-en.js'),
  '// Generado por i18n/build.mjs desde i18n/en.json: no editar a mano.\n// Generated by i18n/build.mjs from i18n/en.json: do not edit by hand.\nexport default ' + json.trimEnd() + ';\n');
const assets = join(root, 'android/app/src/main/assets/i18n');
mkdirSync(assets, { recursive: true });
writeFileSync(join(assets, 'en.json'), json);
console.log(`${Object.keys(sorted).length} textos → web/js/i18n-en.js y android/app/src/main/assets/i18n/en.json`);
